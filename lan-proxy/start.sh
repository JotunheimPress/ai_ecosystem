#!/usr/bin/env bash
# LAN proxy: one Caddy container that is the stack's only door to the local network. It
# serves each app over HTTPS on its own port, with a certificate from its own local CA,
# and asks for a password in front of the apps that have no login. See CLAUDE.md.
#
# Usage:
#   ./start.sh NAME     (re)start, serving the apps at https://NAME:<port>
#                       NAME = a host name (myhost.local) or an IPv4 address
# Normally run by `stack lan on`, which also switches Pantheon and Iguana to accept NAME.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# ai-stack/lan-proxy -> ai-stack -> the ecosystem root (projects are siblings).
ECO="${AI_ECOSYSTEM:-$(dirname "$(dirname "$SCRIPT_DIR")")}"
STATE="${LAN_PROXY_STATE:-$ECO/lan-proxy}"   # CA, certs, password: never committed
IMAGE="docker.io/library/caddy:2.11.4"
CONTAINER_NAME="lan-proxy"
NET="ai-net"
LAN_USER="stack"

NAME="${1:?usage: start.sh NAME (host name or IPv4 address)}"
# NAME goes into the Caddyfile and the page, so only plain host names and IPv4 addresses.
if [[ -n "${LAN_PROXY_BIND:-}" && ! "$LAN_PROXY_BIND" =~ ^[0-9.]+$ ]]; then
    echo "LAN_PROXY_BIND must be an IPv4 address: $LAN_PROXY_BIND" >&2; exit 2
fi
if ! [[ "$NAME" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)*$ ]]; then
    echo "not a host name or IPv4 address: $NAME" >&2; exit 2
fi

# app  LAN port  upstream on ai-net    locked = behind the proxy's password (no login of its own)
APPS=(
  "Pantheon      8761 companion:7861      open"
  "Rhapsode      8760 ai-story-maker:7860 locked"
  "Iguana Studio 8762 iguana:7862         locked"
  "Nocturne      8764 nocturne:7864       locked"
)
PAGE_PORT=8780   # plain HTTP: the landing page and the CA certificate to install

mkdir -p "$STATE/data" "$STATE/config" "$STATE/www"
chmod 700 "$STATE"

# The password for the locked apps: made once, kept until `stack lan password` deletes it.
if [[ ! -s "$STATE/password" ]]; then
    # `|| true`: tr is killed by SIGPIPE once head has its 20 characters, and under
    # pipefail + set -e that would end this script silently (it did, on the first start).
    pw=$(LC_ALL=C tr -dc 'a-km-z2-9' </dev/urandom | head -c 20 || true)
    [[ ${#pw} -eq 20 ]] || { echo "could not make a password" >&2; exit 1; }
    ( umask 077; printf '%s' "$pw" > "$STATE/password" )
    rm -f "$STATE/password.hash"
fi
if [[ ! -s "$STATE/password.hash" ]]; then
    podman run --rm "$IMAGE" caddy hash-password --plaintext "$(cat "$STATE/password")" \
        > "$STATE/password.hash.tmp"
    mv "$STATE/password.hash.tmp" "$STATE/password.hash"
fi
HASH="$(cat "$STATE/password.hash")"
[[ "$HASH" =~ ^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$ ]] || { echo "bad password hash in $STATE/password.hash" >&2; exit 1; }

# ---- Caddyfile ------------------------------------------------------------------------
{
cat <<EOF
# Generated by ai-stack/lan-proxy/start.sh. Edits are overwritten on the next start.
{
	admin off
	# Every site gets a certificate from Caddy's own local CA (root in /data/caddy/pki).
	local_certs
	skip_install_trust
	pki {
		ca local {
			name "AI Stack LAN"
		}
	}
}

(locked) {
	basic_auth {
		$LAN_USER $HASH
	}
}
EOF
for row in "${APPS[@]}"; do
    read -r -a f <<<"$row"
    n=${#f[@]}; port=${f[n-3]}; up=${f[n-2]}; mode=${f[n-1]}
    echo
    echo "https://$NAME:$port {"
    [[ $mode == locked ]] && printf '\timport locked\n'
    # Caddy sends X-Forwarded-Proto/Host itself; Pantheon trusts them in LAN mode.
    printf '\treverse_proxy %s\n}\n' "$up"
done
cat <<EOF

# Landing page + the CA certificate, over plain HTTP because a device can't check HTTPS
# until it trusts this CA. Only root.crt is reachable: never serve the pki directory.
http://:$PAGE_PORT {
	handle /ai-stack-lan-ca.crt {
		root * /data/caddy/pki/authorities/local
		rewrite * /root.crt
		header Content-Type application/x-x509-ca-cert
		file_server
	}
	handle {
		root * /srv
		file_server
	}
}
EOF
} > "$STATE/Caddyfile"

# ---- landing page ---------------------------------------------------------------------
{
cat <<EOF
<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>AI Stack on $NAME</title>
<style>
:root{color-scheme:light dark;--bg:#f6f5f2;--fg:#1d1c1a;--dim:#6b6862;--card:#fff;--line:#dedbd4;--acc:#7a4fd0}
@media (prefers-color-scheme:dark){:root{--bg:#141413;--fg:#ecebe7;--dim:#9c9a94;--card:#1f1e1c;--line:#34322e;--acc:#b39af0}}
body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.5 system-ui,sans-serif}
main{max-width:34rem;margin:0 auto;padding:2rem 16px}
h1{font-size:1.4rem;margin:0 0 .25rem}p{color:var(--dim);margin:.25rem 0 1.25rem}
a.app{display:flex;justify-content:space-between;padding:.9rem 1rem;margin:.5rem 0;background:var(--card);
 border:1px solid var(--line);border-radius:10px;color:var(--fg);text-decoration:none}
a.app span{color:var(--dim);font-size:.9rem}a{color:var(--acc)}
ol{padding-left:1.2rem;color:var(--dim)}li{margin:.3rem 0}
</style></head><body><main>
<h1>AI Stack on $NAME</h1>
<p>First time on this device? Install the certificate below, then open an app.</p>
EOF
for row in "${APPS[@]}"; do
    read -r -a f <<<"$row"
    n=${#f[@]}; port=${f[n-3]}; mode=${f[n-1]}
    label="${f[*]:0:n-3}"
    note="own login"; [[ $mode == locked ]] && note="stack password"
    echo "<a class=\"app\" href=\"https://$NAME:$port/\">$label <span>$note</span></a>"
done
cat <<EOF
<h1 style="margin-top:2rem">Certificate</h1>
<ol>
<li><a href="/ai-stack-lan-ca.crt">Download the AI Stack LAN certificate</a>.</li>
<li>Check its SHA-256 fingerprint matches what <code>stack lan</code> prints on the host.</li>
<li>iPhone/iPad: Settings › Profile Downloaded › Install, then Settings › General › About ›
Certificate Trust Settings › turn it on. Android: Settings › Security › Encryption &amp;
credentials › Install a certificate › CA certificate. Desktop: import it as a trusted root
in the browser or the OS.</li>
</ol>
</main></body></html>
EOF
} > "$STATE/www/index.html"

# ---- run ------------------------------------------------------------------------------
podman network exists "$NET" 2>/dev/null || podman network create "$NET" >/dev/null
podman container exists "$CONTAINER_NAME" 2>/dev/null && podman rm -f "$CONTAINER_NAME" >/dev/null

# LAN_PROXY_BIND=127.0.0.1 publishes on loopback only: a dry run that no other machine
# can reach (tests, or checking the certificates before opening the ports).
BIND="${LAN_PROXY_BIND:+$LAN_PROXY_BIND:}"
PUBLISH=(-p "${BIND}$PAGE_PORT:$PAGE_PORT")
for row in "${APPS[@]}"; do
    read -r -a f <<<"$row"; port=${f[${#f[@]}-3]}
    PUBLISH+=(-p "${BIND}$port:$port")
done

echo "Starting LAN proxy for https://$NAME (ports 8760-8764, page :$PAGE_PORT)"
# All interfaces on purpose, even where host.env sets BIND=127.0.0.1: this container is
# the one thing meant to be reachable from the LAN.
podman run -d \
    --name "$CONTAINER_NAME" \
    --restart=on-failure:5 \
    --network "$NET" \
    "${PUBLISH[@]}" \
    -v "$STATE/Caddyfile:/etc/caddy/Caddyfile:ro,z" \
    -v "$STATE/data:/data:z" \
    -v "$STATE/config:/config:z" \
    -v "$STATE/www:/srv:ro,z" \
    "$IMAGE" caddy run --config /etc/caddy/Caddyfile >/dev/null

for _ in $(seq 1 30); do
    if curl -sf -m 2 -o /dev/null "http://127.0.0.1:$PAGE_PORT/" \
       && [[ -s "$STATE/data/caddy/pki/authorities/local/root.crt" ]]; then
        echo "==> LAN proxy up. Logs: podman logs -f $CONTAINER_NAME"; exit 0
    fi
    sleep 0.5
done
echo "LAN proxy did not come up. Logs:" >&2
podman logs --tail 15 "$CONTAINER_NAME" 2>&1 | sed 's/^/    /' >&2
exit 1
